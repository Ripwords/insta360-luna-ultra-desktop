#!/usr/bin/env node
// Bundles app/obs/player.ts into the page the webcam server serves at /obs.
// The output is committed, so the Rust build needs no JavaScript toolchain;
// tests/obsPlayer.test.ts fails when it is out of date.
//
//   bun scripts/build-obs-player.mjs
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = new URL("../", import.meta.url);
export const OUTPUT = fileURLToPath(new URL("src-tauri/src/webcam/obs.html", root));

export async function buildObsPage() {
  const result = await build({
    entryPoints: [fileURLToPath(new URL("app/obs/player.ts", root))],
    bundle: true,
    format: "iife",
    minify: true,
    // OBS 30's Browser Source runs Chromium 103 or later.
    target: "chrome103",
    write: false,
    legalComments: "none",
  });
  const script = result.outputFiles[0].text.trim();
  if (script.includes("</script")) throw new Error("the bundle would close its own <script> tag");
  return `<!doctype html>
<!-- Generated by scripts/build-obs-player.mjs from app/obs/player.ts. Do not edit. -->
<html lang="en">
<head>
<meta charset="utf-8">
<title>Luna Ultra webcam</title>
<style>
html,body{margin:0;height:100%;overflow:hidden;background:#000}
canvas{display:block;width:100%;height:100%;object-fit:contain}
p{position:fixed;inset:auto 0 0;margin:0;padding:24px;color:#fff;font:24px system-ui,sans-serif;text-align:center}
</style>
</head>
<body>
<canvas></canvas>
<p></p>
<script>${script}</script>
</body>
</html>
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, await buildObsPage());
  console.log(`Wrote ${OUTPUT}`);
}
